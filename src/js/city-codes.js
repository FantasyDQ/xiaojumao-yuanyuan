// 模糊匹配城市名（支持"南京市""江苏南京"等）
window.PetApp.findCityCode = function(name) {
  if (!name) return null;
  const codes = window.PetApp.CITY_CODES;
  // 直接匹配
  if (codes[name]) return codes[name];
  // 去掉"市""省""区"后缀
  const stripped = name.replace(/[市区县省]/g, '');
  if (codes[stripped]) return codes[stripped];
  // 包含匹配
  for (const key in codes) {
    if (name.includes(key) || key.includes(stripped)) return codes[key];
  }
  return null;
};
